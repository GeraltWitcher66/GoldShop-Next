/** آیا محصول تخفیف فعال دارد؟ */
export function hasDiscount(product) {
  return Boolean(product?.isSpecialOffer && product.discountPercent > 0);
}

/** قیمت نهایی پس از اعمال درصد تخفیف (بدون اعشار). */
export function getFinalPrice(product) {
  const percent = hasDiscount(product)
    ? Math.min(Math.max(Number(product.discountPercent) || 0, 0), 100)
    : 0;
  return Math.round(product.price * (1 - percent / 100));
}

